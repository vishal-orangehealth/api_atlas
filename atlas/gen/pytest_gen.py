def py_literal(x, indent: int = 0) -> str:
    """Render a value IR as Python source."""
    pad = "    " * indent
    if is_var(x):
        ref = f"v[{x['$var']!r}]"
        return f"str({ref})" if x.get("as") == "str" else ref
    if is_fmt(x):
        parts = []
        for p in x["$fmt"]:
            if is_var(p):
                parts.append("{v[" + repr(p["$var"]) + "]}")
            else:
                parts.append(str(p).replace("{", "{{").replace("}", "}}").replace('"', '\\"'))
        return 'f"' + "".join(parts) + '"'
    if isinstance(x, dict):
        if not x:
            return "{}"
        items = [f"{pad}    {json.dumps(str(k))}: {py_literal(v, indent + 1)}," for k, v in x.items()]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(x, list):
        if not x:
            return "[]"
        if all(not isinstance(i, (dict, list)) for i in x) and len(x) <= 6:
            return "[" + ", ".join(py_literal(i, indent) for i in x) + "]"
        items = [f"{pad}    {py_literal(v, indent + 1)}," for v in x]
        return "[\n" + "\n".join(items) + f"\n{pad}]"
    if x is True:
        return "True"
    if x is False:
        return "False"
    if x is None:
        return "None"
    if isinstance(x, str):
        return json.dumps(x, ensure_ascii=False)
    return repr(x)


def _path_expr(path_ir: list) -> str:
    parts = []
    for p in path_ir:
        if is_var(p):
            parts.append("{v[" + repr(p["$var"]) + "]}")
        else:
            parts.append(str(p).replace("{", "{{").replace("}", "}}").replace('"', '\\"'))
    s = "/" + "/".join(parts)
    return f'f"{s}"' if any(is_var(p) for p in path_ir) else json.dumps(s)


def _access(base: str, path: list) -> str:
    return base + "".join(f"[{p!r}]" for p in path)


def _assign_line(name: str, spec: dict) -> str:
    k = spec["kind"]
    if k == "env":
        d = spec.get("default")
        return f"v[{name!r}] = env({spec['env']!r}" + (f", {d!r})" if d is not None else ")")
    if k == "unique":
        u = spec["unique"]
        if u == "email":
            return f"v[{name!r}] = unique_email()"
        if u == "phone":
            return f"v[{name!r}] = unique_phone()"
        return f"v[{name!r}] = unique_string({spec.get('base', 'atlas')!r})"
    return f"v[{name!r}] = {py_literal(spec.get('value'))}"


def _request_lines(step: dict, var_specs: dict, client: str = "api") -> list[str]:
    lines = [_assign_line(n, var_specs[n]) for n in step["assigns"] if n in var_specs]
    args = [json.dumps(step["method"]), _path_expr(step["path"])]
    if step["host_index"]:
        args.append(f"host={step['host_index']}")
    if step["query"]:
        keys = [k for k, _ in step["query"]]
        if len(set(keys)) == len(keys):
            args.append("params=" + py_literal({k: val for k, val in step["query"]}, 1))
        else:  # repeated keys (?tag=a&tag=b) need a list of pairs
            pairs = ", ".join(f"({json.dumps(k)}, {py_literal(val)})" for k, val in step["query"])
            args.append(f"params=[{pairs}]")
    if step["headers"]:
        args.append("headers=" + py_literal(step["headers"], 1))
    kind = step["body_kind"]
    if kind == "json":
        args.append("json=" + py_literal(step["body"], 1))
    elif kind == "form":
        args.append("data=" + py_literal(step["body"], 1))
    elif kind == "text" and step["body"] is not None:
        args.append("data=" + py_literal(step["body"], 1))
    joined = ",\n    ".join(args)
    lines.append(f"r = {client}.request(\n    {joined},\n)")
    return lines


def _expect_line(expect: dict) -> str:
    if "status" in expect:
        return f"assert r.status_code == {int(expect['status'])}, r.text"
    if "status_in" in expect:
        return f"assert r.status_code in {tuple(expect['status_in'])}, r.text"
    lo, hi = expect["status_range"]
    return f"assert {lo} <= r.status_code <= {hi}, r.text"


PY_TYPES = {"string": "str", "integer": "int", "number": "(int, float)", "boolean": "bool",
            "object": "dict", "array": "list", "null": "type(None)"}


def _assertion_lines(assertions: list[dict]) -> list[str]:
    if not assertions:
        return []
    lines = ["body = r.json()"]
    for a in assertions:
        path = a["path"]
        guard = ""
        if path and path[0] == "*":
            guard = "if body: "
            expr = _access("body[0]", path[1:])
        else:
            expr = _access("body", path)
        if a["check"] == "type":
            lines.append(f"{guard}assert isinstance({expr}, {PY_TYPES.get(a['type'], 'object')})")
        elif a["check"] == "equals":
            lines.append(f"{guard}assert {expr} == {py_literal(a['value'])}")
        elif a["check"] == "present":
            parent = _access("body[0]" if guard else "body", path[1:-1] if guard else path[:-1])
            lines.append(f"{guard}assert {path[-1]!r} in {parent}")
    return lines


def _extract_lines(step: dict) -> list[str]:
    lines = []
    for ex in step["extract"]:
        if ex["source"] == "body":
            lines.append(f"v[{ex['var']!r}] = {_access('r.json()', ex['path'])}")
        elif ex["source"] == "header":
            lines.append(f"v[{ex['var']!r}] = r.headers[{ex['path'][0]!r}]")
    return lines


def _drop_needless_str(step: dict, specs: dict) -> dict:
    """str(v["x"]) only when x might not already be a string."""
    def walk(x):
        if is_var(x):
            spec = specs.get(x["$var"], {})
            stringy = spec.get("kind") in ("env", "unique") or spec.get("vtype") == "string" or \
                (spec.get("kind") == "literal" and isinstance(spec.get("value"), str))
            if x.get("as") == "str" and stringy:
                return {"$var": x["$var"], "as": "raw"}
            return x
        if is_fmt(x):
            return x
        if isinstance(x, dict):
            return {k: walk(v) for k, v in x.items()}
        if isinstance(x, list):
            return [walk(v) for v in x]
        return x
    step = dict(step)
    for k in ("query", "headers", "body"):
        step[k] = walk(step[k])
    if step["query"]:
        step["query"] = [list(q) for q in step["query"]]
    return step


def generate(cases: list[dict], hosts: list[str], suite_name: str = "app") -> dict[str, str]:
    """Return {filename: content}."""
    helpers: dict[str, str] = {}        # name -> source
    helper_for: dict[str, str] = {}     # source -> name
    used_helper_names: set[str] = set()
    tests: list[str] = []
    used_test_names: set[str] = set()
    env_vars: set[str] = set()

    def helper(step: dict, var_specs: dict) -> str:
        step = _drop_needless_str(step, var_specs)
        body = _request_lines(step, var_specs)
        body.append(_expect_line(step["expect"]))
        body += _extract_lines(step)
        body.append("return r")
        inner = "\n    ".join("\n".join(body).split("\n"))
        src_body = f'    """{step["label"]}"""\n    {inner}\n'
        if src_body in helper_for:
            return helper_for[src_body]
        name = unique_name(ident(step["name"], 60) or "step", used_helper_names)
        helper_for[src_body] = name
        helpers[name] = f"def {name}(api, v):\n{src_body}"
        return name

    for case in cases:
        specs = case["vars"]
        for spec in specs.values():
            if spec.get("kind") == "env":
                env_vars.add(spec["env"])
        lines = []
        for step in case["setup"]:
            lines.append(f"{helper(step, specs)}(api, v)")
        if case["setup"]:
            lines.append("")
        t = _drop_needless_str(case["target"], specs)
        client = "api.fresh()" if t.get("fresh_session") else "api"
        lines += _request_lines(t, specs, client)
        lines.append(_expect_line(t["expect"]))
        lines += _assertion_lines(t["assertions"])
        name = unique_name("test_" + ident(case["title"], 70), used_test_names)
        doc = f'    """{case["title"]}  [{case["kind"]}]"""'
        body = "\n    ".join("\n".join(lines).split("\n"))
        body = "\n".join(l.rstrip() for l in body.split("\n"))
        tests.append(f"def {name}(api, v):\n{doc}\n    {body}\n")

    module = [
        f'"""API tests for {suite_name}. Generated by API Atlas.\n\nRun:  pytest -v\n"""',
        "from atlas_support import env, unique_email, unique_phone, unique_string  # noqa: F401",
        "",
        "",
        "# ---- setup steps (reused by the tests below) ----",
        "",
    ]
    for src in helpers.values():
        module += [src, ""]
    module += ["# ---- tests ----", ""]
    for t in tests:
        module += [t, ""]
    test_src = "\n".join(module).rstrip() + "\n"

    base_urls = "\n".join(
        f'    os.environ.get("ATLAS_BASE_URL{"" if i == 0 else "_" + str(i + 1)}", {h!r}),'
        for i, h in enumerate(hosts or ["http://localhost"])
    )
    readme = _readme(suite_name, hosts, sorted(env_vars), len(cases))
    return {
        f"test_{ident(suite_name, 40) or 'app'}_api.py": test_src,
        "atlas_support.py": SUPPORT.format(base_urls=base_urls),
        "conftest.py": CONFTEST,
        "requirements.txt": "pytest>=7\nrequests>=2.28\n",
        "README.md": readme,
    }


def _readme(name, hosts, env_vars, n) -> str:
    env_lines = "\n".join(f"export {e}=..." for e in env_vars) or "# nothing to set"
    base = "\n".join(
        f"- `ATLAS_BASE_URL{'' if i == 0 else '_' + str(i + 1)}` (default `{h}`)" for i, h in enumerate(hosts))
    return f"""# {name} API tests

Generated by API Atlas: {n} test(s), pytest + requests.

## Run

```bash
pip install -r requirements.txt
{env_lines}
pytest -v
```

## Settings

{base}
- `ATLAS_TIMEOUT` request timeout in seconds (default 30)

Values that were masked during capture (passwords, tokens, account emails) are read from
environment variables. Sign-up flows get a fresh unique email/phone on every run.
"""
