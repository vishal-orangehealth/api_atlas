SUPPORT = '''"""Helpers used by the generated tests. Generated by API Atlas - safe to edit."""
import os
import random
import string
import uuid

import pytest
import requests

BASE_URLS = [
{base_urls}
]
TIMEOUT = float(os.environ.get("ATLAS_TIMEOUT", "30"))


def env(name, default=None):
    """Read a secret or account value from the environment."""
    value = os.environ.get(name, default)
    if value is None or value == "":
        pytest.fail(f"Set the {{name}} environment variable before running these tests.")
    return value


def unique_email():
    return f"atlas_{{uuid.uuid4().hex[:10]}}@example.com"


def unique_phone():
    return "9" + "".join(random.choices(string.digits, k=9))


def unique_string(base="atlas"):
    return f"{{base}}_{{uuid.uuid4().hex[:8]}}"


class Api:
    """A requests.Session that knows the base URL(s) of the app under test."""

    def __init__(self):
        self.session = requests.Session()

    def request(self, method, path, host=0, **kwargs):
        kwargs.setdefault("timeout", TIMEOUT)
        return self.session.request(method, BASE_URLS[host].rstrip("/") + path, **kwargs)

    def fresh(self):
        """A new client with no cookies, for "without auth" checks."""
        return Api()

    def close(self):
        self.session.close()
'''

